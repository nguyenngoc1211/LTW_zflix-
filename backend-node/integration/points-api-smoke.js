import { config } from 'dotenv';
config({ path: '../.env' });
import assert from 'node:assert/strict';
import jwt from 'jsonwebtoken';
import request from 'supertest';
import { MongoClient } from 'mongodb';

const name = process.env.COMMUNITY_TEST_DB_NAME;
if (name !== 'community_test_schema_20261101' || !process.env.COMMUNITY_TEST_MONGODB_URI || name.toLowerCase() === process.env.MONGODB_DB_NAME?.toLowerCase()) throw new Error('Dedicated test DB required');
process.env.MONGODB_URI = process.env.COMMUNITY_TEST_MONGODB_URI;
process.env.MONGODB_DB_NAME = name;
process.env.DATA_STORE = 'mongodb';
process.env.JWT_ACCESS_SECRET ||= 'points-test-secret-with-at-least-thirty-two-characters';
const { default: app } = await import('../src/app.js');
const { closeMongo } = await import('../src/core/database/mongo.js');
const client = new MongoClient(process.env.MONGODB_URI, { serverSelectionTimeoutMS: 10000 });
const ids = [2147482301, 2147482302, 2147482304], productionId = 2147482303;
const sessions = ids.map((id) => `points-api-smoke:${id}`);
try {
  await client.connect();
  const db = client.db(name);
  assert.equal(db.databaseName, 'community_test_schema_20261101');
  await db.command({ ping: 1 });
  for (const id of ids) assert.equal(await db.collection('users').findOne({ id }), null, 'Fixture user exists');
  assert.equal(await db.collection('productions').findOne({ id: productionId }), null, 'Fixture movie exists');
  await db.collection('users').insertMany(ids.map((id, index) => ({ _id: id, id, username: `points_api_${id}`, status: 'active', role: index === 2 ? 'admin' : 'user' })));
  const expiry = new Date(Date.now() + 3600000);
  await db.collection('auth_sessions').insertMany(ids.map((id, index) => ({ _id: sessions[index], id: sessions[index], user_id: id, revoked_at: null, expires_at: expiry, absolute_expires_at: expiry })));
  await db.collection('productions').insertOne({ _id: productionId, id: productionId, title: 'Points test film', type: 'movie' });
  const auth = (index) => `Bearer ${jwt.sign({ sid: sessions[index] }, process.env.JWT_ACCESS_SECRET, { subject: String(ids[index]), algorithm: 'HS256' })}`;
  const post = await request(app).post('/api/v1/community/posts').set('Authorization', auth(0)).send({ title: 'A worthwhile movie discussion', content: 'This post contains a detailed community discussion about a film.' });
  assert.equal(post.status, 201, JSON.stringify(post.body));
  const review = await request(app).post('/api/v1/community/posts').set('Authorization', auth(0)).send({ title: 'A detailed review of this film', content: 'This movie has strong performances and a thoughtful ending.', category: 'review', productionId, rating: 4 });
  assert.equal(review.status, 201, JSON.stringify(review.body));
  assert.equal((await request(app).get('/api/v1/points/me').set('Authorization', auth(0))).body.monthlyPoints, 25, 'Review is not double-counted');
  assert.equal((await request(app).put(`/api/v1/community/posts/${post.body.id}/vote`).set('Authorization', auth(0)).send({ value: 1 })).status, 400);
  const vote = await request(app).put(`/api/v1/community/posts/${post.body.id}/vote`).set('Authorization', auth(1)).send({ value: 1 });
  assert.equal(vote.status, 200, JSON.stringify(vote.body));
  assert.equal((await request(app).get('/api/v1/points/me').set('Authorization', auth(0))).body.monthlyPoints, 27);
  const comment = await request(app).post(`/api/v1/community/posts/${post.body.id}/comments`).set('Authorization', auth(1)).send({ content: 'This is a thoughtful reply to the film discussion.' });
  assert.equal(comment.status, 201, JSON.stringify(comment.body));
  assert.equal((await request(app).get('/api/v1/points/me').set('Authorization', auth(1))).body.monthlyPoints, 3);
  const duplicateComment = await request(app).post(`/api/v1/community/posts/${post.body.id}/comments`).set('Authorization', auth(1)).send({ content: 'This is a thoughtful reply to the film discussion.' });
  assert.equal(duplicateComment.status, 201, JSON.stringify(duplicateComment.body));
  assert.equal((await request(app).get('/api/v1/points/me').set('Authorization', auth(1))).body.monthlyPoints, 3, 'Repeated text earns no points');
  assert.equal((await request(app).delete(`/api/v1/community/posts/${post.body.id}/comments/${comment.body.id}`).set('Authorization', auth(1))).status, 204);
  assert.equal((await request(app).get('/api/v1/points/me').set('Authorization', auth(1))).body.monthlyPoints, 0);
  assert.equal((await request(app).delete(`/api/v1/community/posts/${post.body.id}`).set('Authorization', auth(0))).status, 204);
  assert.equal((await request(app).get('/api/v1/points/me').set('Authorization', auth(0))).body.monthlyPoints, 15);
  const report = await request(app).post(`/api/v1/community/posts/${review.body.id}/reports`).set('Authorization', auth(1)).send({ reason: 'spam', description: 'Confirmed test violation' });
  assert.equal(report.status, 201, JSON.stringify(report.body));
  const reportId = `community-post:${review.body.id}:${ids[1]}`;
  const confirmed = await request(app).post(`/api/v1/admin/points/reports/${encodeURIComponent(reportId)}/confirm`).set('Authorization', auth(2)).send({ reason: 'Confirmed invalid content after review' });
  assert.equal(confirmed.status, 200, JSON.stringify(confirmed.body));
  assert.equal((await request(app).get('/api/v1/points/me').set('Authorization', auth(0))).body.monthlyPoints, 0);
  assert.equal((await request(app).get('/api/v1/points/me').set('Authorization', auth(1))).body.monthlyPoints, 5);
  const movieComment = await request(app).post(`/api/v1/productions/${productionId}/comments`).set('Authorization', auth(0)).send({ content: 'This film has a memorable ending and strong performances.' });
  assert.equal(movieComment.status, 201, JSON.stringify(movieComment.body));
  assert.equal((await request(app).get('/api/v1/points/me').set('Authorization', auth(0))).body.monthlyPoints, 3);
  assert.equal((await request(app).put(`/api/v1/comments/${movieComment.body.id}/vote`).set('Authorization', auth(1)).send({ value: 1 })).status, 200);
  assert.equal((await request(app).get('/api/v1/points/me').set('Authorization', auth(0))).body.monthlyPoints, 5);
  assert.equal((await request(app).delete(`/api/v1/comments/${movieComment.body.id}`).set('Authorization', auth(0))).status, 204);
  assert.equal((await request(app).get('/api/v1/points/me').set('Authorization', auth(0))).body.monthlyPoints, 0);
  const moderatedComment = await request(app).post(`/api/v1/productions/${productionId}/comments`).set('Authorization', auth(0)).send({ content: 'The soundtrack gives this movie a distinct atmosphere.' });
  assert.equal(moderatedComment.status, 201, JSON.stringify(moderatedComment.body));
  assert.equal((await request(app).delete(`/api/v1/admin/comments/${moderatedComment.body.id}`).set('Authorization', auth(2))).status, 204);
  assert.equal((await request(app).get('/api/v1/points/me').set('Authorization', auth(0))).body.monthlyPoints, 0);
  const adjustment = { userId: ids[0], points: 7, reason: 'Verified points smoke adjustment', requestId: 'points-smoke-adjust-001' };
  assert.equal((await request(app).post('/api/v1/admin/points/adjustments').set('Authorization', auth(1)).send(adjustment)).status, 403);
  assert.equal((await request(app).post('/api/v1/admin/points/adjustments').set('Authorization', auth(2)).send(adjustment)).status, 201);
  assert.equal((await request(app).post('/api/v1/admin/points/adjustments').set('Authorization', auth(2)).send(adjustment)).body.idempotent, true);
  assert.equal((await request(app).get('/api/v1/points/me').set('Authorization', auth(0))).body.monthlyPoints, 7);
  console.log('Points API smoke passed on', db.databaseName);
} finally {
  if (client.topology?.isConnected()) {
    const db = client.db(name);
    const posts = await db.collection('community_posts').find({ author_id: ids[0] }, { projection: { _id: 1 } }).toArray();
    const postIds = posts.map((item) => item._id);
    const comments = await db.collection('community_post_comments').find({ post_id: { $in: postIds } }, { projection: { _id: 1 } }).toArray();
    const movieComments = await db.collection('comments').find({ production_id: productionId, user_id: { $in: ids } }, { projection: { id: 1 } }).toArray();
    await db.collection('notifications').deleteMany({ user_id: { $in: ids } });
    await db.collection('community_comment_votes').deleteMany({ comment_id: { $in: comments.map((item) => item._id) } });
    await db.collection('community_post_votes').deleteMany({ post_id: { $in: postIds } });
    await db.collection('community_post_comments').deleteMany({ post_id: { $in: postIds } });
    await db.collection('movie_comment_votes').deleteMany({ comment_id: { $in: movieComments.map((item) => item.id) } });
    await db.collection('comments').deleteMany({ production_id: productionId, user_id: { $in: ids } });
    await db.collection('community_reports').deleteMany({ reporter_id: { $in: ids }, target_id: { $in: postIds } });
    await db.collection('community_posts').deleteMany({ _id: { $in: postIds } });
    await db.collection('point_transactions').deleteMany({ userId: { $in: ids } });
    await db.collection('point_admin_audit').deleteMany({ userId: { $in: ids } });
    await db.collection('point_daily_quotas').deleteMany({ userId: { $in: ids } });
    await db.collection('point_content_fingerprints').deleteMany({ userId: { $in: ids } });
    await db.collection('productions').deleteOne({ id: productionId });
    await db.collection('auth_sessions').deleteMany({ _id: { $in: sessions } });
    await db.collection('users').deleteMany({ id: { $in: ids } });
  }
  await closeMongo(); await client.close();
}
