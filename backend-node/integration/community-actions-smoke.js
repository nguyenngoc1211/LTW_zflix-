import 'dotenv/config';
import assert from 'node:assert/strict';
import { randomInt } from 'node:crypto';
import jwt from 'jsonwebtoken';
import request from 'supertest';
import { createApp } from '../src/app.js';
import { securityConfig } from '../src/config/security.config.js';
import { connectMongo, closeMongo, mongoCollection } from '../src/core/database/mongo.js';

const expected = 'community_test_schema_20261101';
if (process.env.DATA_STORE !== 'mongodb' || !process.env.COMMUNITY_TEST_MONGODB_URI) throw new Error('Dedicated MongoDB test URI required');
process.env.MONGODB_URI = process.env.COMMUNITY_TEST_MONGODB_URI;
process.env.MONGODB_DB_NAME = expected;
const db = await connectMongo();
if (db.databaseName !== expected) throw new Error(`Refusing test writes to ${db.databaseName}`);
const seed = randomInt(300000000, 700000000);
const authorId = seed, reporterId = seed + 1, moderatorId = seed + 2, adminId = seed + 3;
const postId = seed + 4, parentId = seed + 5, replyId = seed + 6;
const ids = [authorId, reporterId, moderatorId, adminId];
const now = new Date(), expires = new Date(now.getTime() + 3600000);
const app = createApp();
const auth = (id) => ({ Authorization: `Bearer ${jwt.sign({ sid: id }, securityConfig.jwtAccessSecret, { subject: String(id), expiresIn: '5m', algorithm: 'HS256' })}` });
try {
  await (await mongoCollection('users')).insertMany(ids.map((id) => ({ _id: id, id, username: `action_${id}`, email: `action_${id}@example.test`, role: id === adminId ? 'admin' : id === moderatorId ? 'moderator' : 'user', status: 'active' })));
  await (await mongoCollection('auth_sessions')).insertMany(ids.map((id) => ({ _id: id, id, user_id: id, refresh_token_hash: `action_${id}`, revoked_at: null, expires_at: expires, absolute_expires_at: expires })));
  await (await mongoCollection('community_posts')).insertOne({ _id: postId, id: postId, author_id: authorId, content_type: 'community_post', type: 'normal', category: 'discussion', title: 'Bài thảo luận hợp lệ', content: 'Nội dung bài thảo luận đủ dài để thử menu thao tác cộng đồng.', visibility: 'public', status: 'active', comment_count: 2, created_at: now, updated_at: now });
  await (await mongoCollection('community_post_comments')).insertMany([{ _id: parentId, id: parentId, post_id: postId, author_id: authorId, content: 'Bình luận gốc cần quản lý trong cộng đồng.', status: 'active', created_at: now, updated_at: now }, { _id: replyId, id: replyId, post_id: postId, parent_id: parentId, author_id: authorId, content: 'Nội dung reply ban đầu cần quản lý.', status: 'active', created_at: now, updated_at: now }]);
  let response = await request(app).patch(`/api/v1/community/posts/${postId}/comments/${replyId}`).set(auth(reporterId)).send({ content: 'Người khác không được sửa reply.' });
  assert.equal(response.status, 404);
  response = await request(app).patch(`/api/v1/community/posts/${postId}/comments/${replyId}`).set(auth(authorId)).send({ content: 'Nội dung reply đã chỉnh sửa hợp lệ.', isSpoiler: false });
  assert.equal(response.status, 200, JSON.stringify(response.body));
  response = await request(app).post(`/api/v1/community/posts/${postId}/comments/${replyId}/reports`).set(auth(authorId)).send({ reason: 'spam', description: '' });
  assert.equal(response.status, 404);
  response = await request(app).post(`/api/v1/community/posts/${postId}/comments/${replyId}/reports`).set(auth(reporterId)).send({ reason: 'inappropriate', description: 'Cần xem xét nội dung' });
  assert.equal(response.status, 201, JSON.stringify(response.body));
  response = await request(app).post(`/api/v1/community/posts/${postId}/comments/${replyId}/reports`).set(auth(reporterId)).send({ reason: 'spam', description: '' });
  assert.equal(response.status, 409);
  response = await request(app).get('/api/v1/admin/moderation/reports?status=open').set(auth(adminId));
  assert.equal(response.status, 200);
  const report = response.body.items.find((item) => item.target_id === replyId);
  assert.equal(report.post_id, postId);
  assert.equal(report.target_excerpt, 'Nội dung reply đã chỉnh sửa hợp lệ.');
  response = await request(app).get(`/api/v1/community/posts/${postId}/comments?parentId=${parentId}`).set(auth(reporterId));
  assert.equal(response.status, 200);
  assert.equal(response.body.items[0].id, replyId);
  response = await request(app).delete(`/api/v1/community/posts/${postId}/comments/${replyId}`).set(auth(reporterId));
  assert.equal(response.status, 404);
  response = await request(app).delete(`/api/v1/community/posts/${postId}/comments/${replyId}`).set(auth(moderatorId));
  assert.equal(response.status, 204, JSON.stringify(response.body));
  response = await request(app).get(`/api/v1/community/posts/${postId}/comments`).set(auth(reporterId));
  assert.equal(response.status, 200);
  assert.equal(response.body.items[0].reply_count, 0);
  assert.equal(response.body.items[0].thread_count, 1);
  assert.equal((await (await mongoCollection('community_posts')).findOne({ _id: postId })).comment_count, 1);
  assert.equal(await (await mongoCollection('moderation_audit')).countDocuments({ actorId: moderatorId, targetId: replyId, source: 'admin_content' }), 1);
  response = await request(app).delete(`/api/v1/community/posts/${postId}/comments/${replyId}`).set(auth(moderatorId));
  assert.equal(response.status, 404);
  response = await request(app).post(`/api/v1/community/posts/${postId}/reports`).set(auth(reporterId)).send({ reason: 'inappropriate', description: '' });
  assert.equal(response.status, 201);
  response = await request(app).delete(`/api/v1/community/posts/${postId}`).set(auth(moderatorId));
  assert.equal(response.status, 204);
  assert.equal(await (await mongoCollection('moderation_audit')).countDocuments({ actorId: moderatorId, targetId: postId, source: 'admin_content' }), 1);
  console.log('community actions smoke passed: owner edit, report self/duplicate/preview, moderator delete, reply count and audit');
} finally {
  await (await mongoCollection('moderation_audit')).deleteMany({ actorId: moderatorId, targetId: { $in: [replyId, postId] } });
  await (await mongoCollection('community_reports')).deleteMany({ reporter_id: reporterId, target_id: { $in: [replyId, postId] } });
  await (await mongoCollection('point_transactions')).deleteMany({ userId: { $in: ids } });
  await (await mongoCollection('point_daily_quotas')).deleteMany({ userId: { $in: ids } });
  await (await mongoCollection('point_content_fingerprints')).deleteMany({ userId: { $in: ids } });
  await (await mongoCollection('community_post_comments')).deleteMany({ _id: { $in: [parentId, replyId] } });
  await (await mongoCollection('community_posts')).deleteOne({ _id: postId });
  await (await mongoCollection('auth_sessions')).deleteMany({ user_id: { $in: ids } });
  await (await mongoCollection('users')).deleteMany({ id: { $in: ids } });
  await closeMongo();
}
